#!/usr/bin/env python3
"""Generate the README flag reference and theme table from the live CLI.

Builds the real argparse parser (global flags plus the plugin
schema-generated flags) and renders it into the README between the
FLAG-REF / THEME-TABLE markers, so the documentation cannot drift from
the actual CLI.

Usage:
    python scripts/generate_flag_reference.py           # update README.md
    python scripts/generate_flag_reference.py --check   # exit 1 if stale

The check mode is meant for CI: it fails when the generated tables no
longer match the README.
"""

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
README = REPO_ROOT / "README.md"

FLAG_BEGIN = "<!-- FLAG-REF:BEGIN (generated by scripts/generate_flag_reference.py - do not edit by hand) -->"
FLAG_END = "<!-- FLAG-REF:END -->"
THEME_BEGIN = "<!-- THEME-TABLE:BEGIN (generated by scripts/generate_flag_reference.py - do not edit by hand) -->"
THEME_END = "<!-- THEME-TABLE:END -->"


def build_live_parser():
    """The exact parser the CLI builds at startup, plugins included."""
    from audio_visualizer.__main__ import build_parser
    from audio_visualizer.visualizers.registry import PluginRegistry

    registry = PluginRegistry()
    registry.load_all()
    return build_parser(registry)


def _cell(text: str) -> str:
    """Make a string safe for a markdown table cell."""
    return text.replace("|", "\\|").replace("\n", " ").strip()


def _describe_choices(choices) -> str:
    """Render a choices list; compress contiguous integer ranges (0-51)."""
    if all(isinstance(c, int) and not isinstance(c, bool) for c in choices) and len(choices) > 4:
        nums = sorted(set(choices))
        if nums == list(range(nums[0], nums[-1] + 1)):
            return f"one of: {nums[0]}-{nums[-1]}"
    return "one of: " + ", ".join(str(c) for c in choices)


def _takes(action) -> str:
    """What value an action consumes, e.g. 'str', 'int (one or more)'."""
    if action.nargs == 0:  # store_true / store_false: bare flag, no value
        return "flag (no value)"
    if action.nargs == "?" and action.const is not None:
        return "flag or VALUE"
    type_name = action.type.__name__ if action.type in (int, float, str) else "str"
    if action.choices is not None:
        base = _describe_choices(action.choices)
    else:
        base = type_name
    if action.nargs == "+":
        base += " (one or more)"
    elif action.nargs == "*":
        base += " (zero or more)"
    return base


def _default(action) -> str:
    d = action.default
    if d is None or d == argparse.SUPPRESS:
        return "\u2014"  # em dash
    if isinstance(d, (list, tuple)):
        return "[" + ", ".join(repr(x) for x in d) + "]"
    return repr(d)


def render_flag_tables(parser) -> str:
    out: list[str] = []
    for group in parser._action_groups:
        actions = [a for a in group._group_actions if a.help != argparse.SUPPRESS]
        if not actions:
            continue
        if group.title == "positional arguments":
            title = "Positional arguments"
        elif group.title in ("optional arguments", "options"):
            title = "Global options"
        else:
            title = group.title
        out.append(f"#### {title}\n")
        out.append("| Flag | Takes | Default | Description |")
        out.append("| --- | --- | --- | --- |")
        for a in actions:
            if a.option_strings:
                flag = "`, `".join(a.option_strings)
            else:
                flag = f"`{a.metavar or a.dest}`"
            out.append(
                f"| {flag} | {_cell(_takes(a))} | {_cell(_default(a))} | {_cell(a.help or '')} |"
            )
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def render_theme_table() -> str:
    from audio_visualizer.config import COLOR_THEMES

    lines = ["| Theme | Palette |", "| --- | --- |"]
    for name in COLOR_THEMES:
        lines.append(f"| `{name}` | {COLOR_THEMES[name]} |")
    return "\n".join(lines) + "\n"


def _replace_region(text: str, begin: str, end: str, content: str) -> str:
    start = text.index(begin) + len(begin)
    stop = text.index(end, start)
    return text[:start] + "\n" + content.rstrip() + "\n" + text[stop:]


def generate() -> dict[str, str]:
    parser = build_live_parser()
    return {
        "flags": render_flag_tables(parser),
        "themes": render_theme_table(),
    }


def update_readme(content: dict[str, str]) -> None:
    text = README.read_text(encoding="utf-8")
    for marker, key in ((FLAG_BEGIN, "flags"), (THEME_BEGIN, "themes")):
        if (
            marker not in text
            or (marker + "END") not in text
            and (marker.split(":")[0] + ":END") not in text
        ):
            raise SystemExit(f"README.md is missing the {key} marker; re-add {marker!r}")
    text = _replace_region(text, FLAG_BEGIN, FLAG_END, content["flags"])
    text = _replace_region(text, THEME_BEGIN, THEME_END, content["themes"])
    README.write_text(text, encoding="utf-8")
    print(
        f"Updated {README.name}: flag reference ({content['flags'].count(chr(10))} lines) "
        f"and theme table"
    )


def check_readme(content: dict[str, str]) -> bool:
    text = README.read_text(encoding="utf-8")
    ok = True
    for begin, end, key in ((FLAG_BEGIN, FLAG_END, "flags"), (THEME_BEGIN, THEME_END, "themes")):
        start = text.find(begin)
        stop = text.find(end)
        if start == -1 or stop == -1:
            print(f"FAIL: README.md is missing the {key} markers")
            ok = False
            continue
        current = text[start + len(begin) : stop].strip()
        if current != content[key].rstrip():
            print(
                f"FAIL: README.md {key} section is out of date (run "
                f"'python scripts/generate_flag_reference.py')"
            )
            ok = False
    return ok


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check", action="store_true", help="fail if the README tables do not match the live CLI"
    )
    args = ap.parse_args()
    content = generate()
    if args.check:
        return 0 if check_readme(content) else 1
    update_readme(content)
    return 0


if __name__ == "__main__":
    sys.exit(main())
